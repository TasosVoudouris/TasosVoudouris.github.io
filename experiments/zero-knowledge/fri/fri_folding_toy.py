"""One algebraic FRI folding step over F_97.

This is NOT a complete FRI protocol. It demonstrates the core identity
f(x)=f_even(x^2)+x f_odd(x^2), then folds to
g(y)=f_even(y)+beta f_odd(y), halving the degree bound/domain size.
"""
P=97

def evalp(coeffs,x):
    r=0
    for c in reversed(coeffs): r=(r*x+c)%P
    return r

def split_even_odd(coeffs):
    return coeffs[0::2], coeffs[1::2]

def fold_coeffs(coeffs,beta):
    even,odd=split_even_odd(coeffs)
    n=max(len(even),len(odd)); out=[]
    for i in range(n):
        a=even[i] if i<len(even) else 0
        b=odd[i] if i<len(odd) else 0
        out.append((a+beta*b)%P)
    while len(out)>1 and out[-1]==0: out.pop()
    return out

def self_test():
    # degree <= 7 over a domain generated by an element of order 16
    f=[3,5,7,2,9,4,1,6]
    beta=11
    # 8 has order 16 in F_97
    w=8
    assert pow(w,16,P)==1 and pow(w,8,P)!=1
    g=fold_coeffs(f,beta)
    even,odd=split_even_odd(f)
    # Pair x and -x; y=x^2 belongs to the squared (half-size) domain.
    for i in range(8):
        x=pow(w,i,P); y=x*x%P
        fx=evalp(f,x); fneg=evalp(f,(-x)%P)
        inv2=pow(2,-1,P); inv2x=pow((2*x)%P,-1,P)
        even_y=(fx+fneg)*inv2%P
        odd_y=(fx-fneg)*inv2x%P
        assert even_y==evalp(even,y)
        assert odd_y==evalp(odd,y)
        assert evalp(g,y)==(even_y+beta*odd_y)%P
    assert len(g)-1 <= (len(f)-1)//2
    print("FRI algebraic folding identity: PASS")
    print("degree-bound halving intuition: PASS")

if __name__=="__main__": self_test()
