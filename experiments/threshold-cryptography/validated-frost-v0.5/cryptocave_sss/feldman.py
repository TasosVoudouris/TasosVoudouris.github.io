"""A small educational implementation of Feldman verifiable secret sharing.

Feldman VSS adds public commitments to the coefficients of a Shamir
polynomial.  A participant can then check that its private share is consistent
with the committed polynomial before accepting it.

The default parameters are deliberately tiny so that every value can be
printed and checked by hand.  They are not secure production parameters.
"""

from __future__ import annotations

import random
from collections.abc import Iterable
from dataclasses import dataclass

if __package__:
    from .field import is_prime
    from .polynomial import evaluate
    from .shamir import RandomSource, Share, ShamirScheme, Sharing
else:
    from field import is_prime
    from polynomial import evaluate
    from shamir import RandomSource, Share, ShamirScheme, Sharing


@dataclass(frozen=True)
class FeldmanParameters:
    """Public cyclic-group parameters.

    ``scalar_modulus`` is the order of the subgroup generated by ``generator``.
    It must also be the modulus of the Shamir sharing.
    """

    group_modulus: int
    scalar_modulus: int
    generator: int

    def __post_init__(self) -> None:
        if not is_prime(self.group_modulus):
            raise ValueError("group_modulus must be prime")
        if not is_prime(self.scalar_modulus):
            raise ValueError("scalar_modulus must be prime")
        if (self.group_modulus - 1) % self.scalar_modulus != 0:
            raise ValueError("scalar_modulus must divide group_modulus - 1")

        generator = self.generator % self.group_modulus
        if generator in (0, 1):
            raise ValueError("generator must be a non-identity group element")
        if pow(generator, self.scalar_modulus, self.group_modulus) != 1:
            raise ValueError("generator is not in the requested subgroup")

        # The scalar modulus is prime.  Therefore a non-identity element whose
        # q-th power is one has order exactly q.
        object.__setattr__(self, "generator", generator)

    @classmethod
    def educational(cls) -> "FeldmanParameters":
        """Return the small group of order 41 inside the units modulo 83."""

        return cls(group_modulus=83, scalar_modulus=41, generator=4)

    def commit(self, scalar: int) -> int:
        """Compute ``g^scalar`` in the public commitment group."""

        return pow(
            self.generator,
            scalar % self.scalar_modulus,
            self.group_modulus,
        )

    def is_subgroup_element(self, element: int) -> bool:
        """Return whether ``element`` is in the commitment subgroup."""

        element %= self.group_modulus
        return (
            element != 0
            and pow(element, self.scalar_modulus, self.group_modulus) == 1
        )


@dataclass(frozen=True)
class FeldmanCommitments:
    """Public coefficient commitments ``C_j = g^a_j``."""

    parameters: FeldmanParameters
    values: tuple[int, ...]

    def __post_init__(self) -> None:
        if not self.values:
            raise ValueError("at least one coefficient commitment is required")
        normalised = tuple(
            value % self.parameters.group_modulus for value in self.values
        )
        if not all(
            self.parameters.is_subgroup_element(value) for value in normalised
        ):
            raise ValueError("every commitment must be a valid subgroup element")
        object.__setattr__(self, "values", normalised)

    @property
    def degree_bound(self) -> int:
        return len(self.values) - 1

    @property
    def public_secret_commitment(self) -> int:
        """Return ``C_0 = g^secret``.

        This value is binding but not hiding.  It is one reason low-entropy
        secrets should not be shared directly with Feldman VSS.
        """

        return self.values[0]

    def expected_share_commitment(self, participant_id: int) -> int:
        """Compute ``product(C_j^(x^j))`` for participant ``x``."""

        q = self.parameters.scalar_modulus
        p = self.parameters.group_modulus
        x = participant_id % q
        result = 1
        for degree, commitment in enumerate(self.values):
            exponent = pow(x, degree, q)
            result = result * pow(commitment, exponent, p) % p
        return result


@dataclass(frozen=True)
class ShareVerification:
    """The verification result for one participant share."""

    share: Share
    accepted: bool
    reason: str


@dataclass(frozen=True)
class VerificationReport:
    """Accepted and rejected shares under one commitment vector."""

    results: tuple[ShareVerification, ...]

    @property
    def accepted(self) -> tuple[Share, ...]:
        return tuple(result.share for result in self.results if result.accepted)

    @property
    def rejected(self) -> tuple[Share, ...]:
        return tuple(result.share for result in self.results if not result.accepted)

    @property
    def all_accepted(self) -> bool:
        return all(result.accepted for result in self.results)


@dataclass(frozen=True)
class VerifiedReconstruction:
    """A reconstructed secret together with the verification audit trail."""

    secret: int
    report: VerificationReport


@dataclass(frozen=True)
class FeldmanDistribution:
    """One Shamir sharing and its public Feldman commitments."""

    sharing: Sharing
    commitments: FeldmanCommitments

    def __post_init__(self) -> None:
        if self.sharing.scheme.modulus != self.commitments.parameters.scalar_modulus:
            raise ValueError("Shamir field and commitment subgroup order must match")
        if self.sharing.degree_bound != self.commitments.degree_bound:
            raise ValueError("sharing and commitment degree bounds must match")


class FeldmanVSS:
    """Feldman verification layered on the Version 0.1 Shamir scheme."""

    def __init__(
        self,
        shamir: ShamirScheme,
        parameters: FeldmanParameters,
    ) -> None:
        if shamir.modulus != parameters.scalar_modulus:
            raise ValueError(
                "the Shamir modulus must equal the commitment subgroup order"
            )
        self.shamir = shamir
        self.parameters = parameters

    @classmethod
    def educational(
        cls,
        num_parties: int = 5,
        threshold: int = 3,
        rng: RandomSource | None = None,
    ) -> "FeldmanVSS":
        """Construct the directly inspectable Version 0.2 parameter set."""

        parameters = FeldmanParameters.educational()
        shamir = ShamirScheme(
            modulus=parameters.scalar_modulus,
            num_parties=num_parties,
            threshold=threshold,
            rng=rng,
        )
        return cls(shamir, parameters)

    def share(self, secret: int) -> FeldmanDistribution:
        """Create one polynomial, its private shares, and public commitments."""

        coefficients = self.shamir.sample_polynomial(secret)
        shares = tuple(
            Share(x, evaluate(coefficients, x, self.shamir.modulus))
            for x in self.shamir.participant_ids
        )
        sharing = Sharing(self.shamir, shares, self.shamir.degree)
        commitments = FeldmanCommitments(
            self.parameters,
            tuple(self.parameters.commit(coefficient) for coefficient in coefficients),
        )
        return FeldmanDistribution(sharing, commitments)

    def verify_share(
        self,
        share: Share,
        commitments: FeldmanCommitments,
    ) -> ShareVerification:
        """Verify one labelled share against the broadcast commitments."""

        if commitments.parameters != self.parameters:
            return ShareVerification(share, False, "wrong commitment parameters")
        if commitments.degree_bound != self.shamir.degree:
            return ShareVerification(share, False, "wrong commitment count")
        if share.x % self.shamir.modulus not in self.shamir.participant_ids:
            return ShareVerification(share, False, "unknown participant identifier")

        left = self.parameters.commit(share.y)
        right = commitments.expected_share_commitment(share.x)
        if left == right:
            return ShareVerification(share, True, "share matches commitments")
        return ShareVerification(share, False, "share does not match commitments")

    def verify_shares(
        self,
        shares: Iterable[Share],
        commitments: FeldmanCommitments,
    ) -> VerificationReport:
        """Verify a collection while rejecting duplicate participant IDs."""

        selected = list(shares)
        if not selected:
            raise ValueError("at least one share is required")
        if any(not isinstance(share, Share) for share in selected):
            raise TypeError("every item must be a Share")

        identifiers = [share.x % self.shamir.modulus for share in selected]
        if len(set(identifiers)) != len(identifiers):
            raise ValueError("duplicate participant identifiers are not allowed")

        return VerificationReport(
            tuple(self.verify_share(share, commitments) for share in selected)
        )

    def reconstruct_verified(
        self,
        shares: Iterable[Share],
        commitments: FeldmanCommitments,
        require_all_valid: bool = False,
    ) -> VerifiedReconstruction:
        """Verify first and reconstruct only from accepted shares."""

        report = self.verify_shares(shares, commitments)
        if require_all_valid and not report.all_accepted:
            raise ValueError("one or more shares failed Feldman verification")
        if len(report.accepted) < self.shamir.threshold:
            raise ValueError("not enough verified shares to reconstruct")

        secret = self.shamir.reconstruct(report.accepted)
        return VerifiedReconstruction(secret, report)


def demo() -> None:
    """Run an honest distribution and one tampering attempt."""

    vss = FeldmanVSS.educational(rng=random.Random(20))
    distribution = vss.share(17)

    print("Secret: 17")
    print("Public coefficient commitments:", distribution.commitments.values)
    print("Honest share verification:")
    for share in distribution.sharing.shares:
        result = vss.verify_share(share, distribution.commitments)
        print(f"  participant {share.x}: {result.accepted}")

    changed = Share(
        distribution.sharing.shares[0].x,
        (distribution.sharing.shares[0].y + 1) % vss.shamir.modulus,
    )
    result = vss.verify_share(changed, distribution.commitments)
    print("Changed first share accepted?", result.accepted)

    reconstructed = vss.reconstruct_verified(
        distribution.sharing.shares[:3],
        distribution.commitments,
    )
    print("Reconstructed from three verified shares:", reconstructed.secret)


if __name__ == "__main__":
    demo()
